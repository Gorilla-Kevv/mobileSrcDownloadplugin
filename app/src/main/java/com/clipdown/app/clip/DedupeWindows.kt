package com.clipdown.app.clip

/**
 * 全链路去重的时间窗口常量 —— **唯一来源**。
 *
 * 阶段 82 抽出：此前三个环节各自硬编码了一个魔法数字，语义重叠又互相不知情，
 * 排查「为什么这条链接没弹提示 / 为什么下载了两次」时无法一眼看出谁拦了谁。
 *
 * 三层是**串联**的，各自职责不同，不要合并成一个窗口：
 *
 * ```
 * 剪贴板/无障碍/分享
 *        │
 *        ▼
 *  ① LinkCenter    ── 硬拦（1s / 15s）：同一 URL 不许重复"发射"到下游
 *        │                                   force 通道（无障碍+借道并发）用 1s 硬窗口
 *        ▼
 *  ② 识别抑制       ── 只拦"自动弹窗"，不拦识别本身（5s / 10min）
 *        │                                  防止地址栏停留时反复弹同一张卡
 *        ▼
 *  ③ enqueue 去重   ── 拦"同一个媒体真的下一次"（15s + 活跃任务）
 * ```
 */
object DedupeWindows {

    /**
     * ① 普通通道的重复发射抑制窗口。
     *
     * 用户在 Instagram 里反复复制同一条链接时，不该每次都弹窗。
     * 取 15s 是因为一次「复制→切回 App→气泡展开→点击」的人机操作通常在这个量级内。
     */
    const val LINK_REEMIT_MS = 15_000L

    /**
     * ① 强制通道（`force = true`）的硬拦窗口。
     *
     * 无障碍服务与借道 Activity 可能在同一帧内各提交一次同一 URL，
     * 这是「点了气泡却下载两次」的已知并发源，因此**即使 force 也拦**，但只拦 1s，
     * 不影响用户 1 秒后主动要求重新识别。
     */
    const val LINK_FORCE_REEMIT_MS = 1_000L

    /**
     * ② 重复下载提示的抑制窗口。
     *
     * 命中「已解析过」后弹确认卡；地址栏停留会持续触发扫描，
     * 没有这个窗口会连续弹。只抑制**提示**，不抑制识别。
     */
    const val PROMPT_SUPPRESS_MS = 5_000L

    /**
     * ② 下载完成后的自动重弹抑制窗口。
     *
     * 下载完成后用户往往还停在原页面，扫描会立刻再次命中同一链接；
     * 这个窗口足够长，避免"刚下完又弹".
     */
    const val AUTO_RESCAN_SUPPRESS_MS = 10 * 60_000L

    /**
     * ③ 同一媒体的自动下载抑制窗口。
     *
     * 与 [DownloadController.enqueue] 的活跃任务检查互补：那个查"还在队列里"，
     * 这个查"刚刚才下过"，覆盖任务已快速完成的情况。
     */
    const val AUTO_DOWNLOAD_MS = 10_000L
}
